function automaticLanguage() {
  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const candidate of candidates) {
    const language = String(candidate ?? "").toLocaleLowerCase();
    if (language === "zh" || language.startsWith("zh-")) return "zh-Hant";
    if (language === "ja" || language.startsWith("ja-")) return "ja";
    if (language === "ko" || language.startsWith("ko-")) return "ko";
    if (language === "en" || language.startsWith("en-")) return "en";
  }
  return "en";
}

export function interfaceLanguageSetting() {
  const value = localStorage.getItem(storageKey) ?? "auto";
  return supportedLanguages.has(value) ? value : "auto";
}

export function resolvedInterfaceLanguage() {
  const value = interfaceLanguageSetting();
  return value === "auto" ? automaticLanguage() : value;
}

export function setInterfaceLanguage(value) {
  const nextValue = supportedLanguages.has(value) ? value : "auto";
  localStorage.setItem(storageKey, nextValue);
  applyTranslations();
  window.dispatchEvent(new CustomEvent("mangakitchen-language-change", {
    detail: { setting: nextValue, resolved: resolvedInterfaceLanguage() },
  }));
}

export function t(key, parameters = {}) {
  const language = resolvedInterfaceLanguage();
  const template = messages[language]?.[key] ?? messages["zh-Hant"][key] ?? key;
  return Object.entries(parameters).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template
  );
}

export function applyTranslations(root = document) {
  document.documentElement.lang = resolvedInterfaceLanguage();
  document.title = t("appTitle");
  for (const element of root.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const [attribute, selector] of [
    ["placeholder", "[data-i18n-placeholder]"],
    ["title", "[data-i18n-title]"],
    ["aria-label", "[data-i18n-aria-label]"],
    ["alt", "[data-i18n-alt]"],
  ]) {
    const dataName = `i18n${attribute.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("")}`;
    for (const element of root.querySelectorAll(selector)) {
      element.setAttribute(attribute, t(element.dataset[dataName]));
    }
  }
}

window.addEventListener("languagechange", () => {
  if (interfaceLanguageSetting() === "auto") {
    applyTranslations();
    window.dispatchEvent(new CustomEvent("mangakitchen-language-change", {
      detail: { setting: "auto", resolved: resolvedInterfaceLanguage() },
    }));
  }
});
